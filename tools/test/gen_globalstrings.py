"""Write tools/test/globalstrings.lua: the game's English sentences (GlobalStrings) that Serene's files name.

The tests load these so ChatLoot, Vendor, ChatCard... parse the same sentences the client prints. The source is
Ketho's BlizzardInterfaceResources, classic_era branch (it matches this client: e.g. its roll sentences start with
"|HlootHistory:%d|h[Loot]|h: "). Run again after a file starts using a new sentence:

    python3 tools/test/gen_globalstrings.py            # downloads the source once into ~/.cache/serene-tools/ref
    python3 tools/test/gen_globalstrings.py <enUS.lua> # or from a file you have
"""
import os, re, sys, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
URL = "https://raw.githubusercontent.com/Ketho/BlizzardInterfaceResources/classic_era/Resources/GlobalStrings/enUS.lua"
CACHE = os.path.expanduser("~/.cache/serene-tools/ref/gs_classic_era.lua")
LINE = re.compile(r'^([A-Z][A-Z0-9_]*) = (".*");\s*$')


def source(path):
    if path:
        return open(path, encoding="utf-8").read()
    if not os.path.exists(CACHE):
        os.makedirs(os.path.dirname(CACHE), exist_ok=True)
        urllib.request.urlretrieve(URL, CACHE)
    return open(CACHE, encoding="utf-8").read()


# (every word in capitals in the addon and the specs; those that name a sentence are kept)
def names_used():
    words = set()
    folders = [ROOT, os.path.join(HERE, "spec")]
    for folder in folders:
        if not os.path.isdir(folder):
            continue
        for name in os.listdir(folder):
            if name.endswith(".lua"):
                text = open(os.path.join(folder, name), encoding="utf-8").read()
                words.update(re.findall(r"\b[A-Z][A-Z0-9_]{2,}\b", text))
    return words


def main(argv):
    strings = {}
    for line in source(argv[1] if len(argv) > 1 else None).splitlines():
        m = LINE.match(line)
        if m:
            strings[m.group(1)] = m.group(2)
    used = sorted(names_used() & set(strings))
    out = os.path.join(HERE, "globalstrings.lua")
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- Generated by tools/test/gen_globalstrings.py: the game's English sentences that Serene names.\n")
        f.write("-- (classic_era GlobalStrings, BlizzardInterfaceResources) Don't edit by hand.\n")
        for name in used:
            f.write(f"{name} = {strings[name]}\n")
    print(f"{out}: {len(used)} strings")


if __name__ == "__main__":
    main(sys.argv)
